# -*- coding: utf-8 -*-
"""
Legacy CoreAPI schema integration.

CoreAPI support was deprecated in Django REST Framework 3.15 and removed
afterwards. The ``coreapi`` package also does not work on Python 3.13+.
Prefer :py:class:`url_filter.integrations.drf.DjangoFilterBackend` which
implements ``get_schema_operation_parameters`` for DRF's OpenAPI schemas.
"""

from __future__ import absolute_import, print_function, unicode_literals

import coreapi
import coreschema
from django import forms

from ..fields import MultipleValuesField
from .drf import DESCRIPTION, URLFilterBackend, iter_filters

__all__ = ["CoreAPIURLFilterBackend", "DESCRIPTION", "FORM_FIELD_TO_SCHEMA"]

FORM_FIELD_TO_SCHEMA = {
    MultipleValuesField: coreschema.Array,
    forms.BooleanField: coreschema.Boolean,
    forms.IntegerField: coreschema.Integer,
    forms.FloatField: coreschema.Number,
}


def _field_to_schema(field, lookup):
    form_field = field.get_form_field(lookup)
    return FORM_FIELD_TO_SCHEMA.get(type(form_field), coreschema.String)(
        description=DESCRIPTION.get(lookup)
    )


def _all_filters(filterset):
    for name, field, lookup in iter_filters(filterset):
        yield coreapi.Field(
            name=name,
            required=False,
            location="query",
            schema=_field_to_schema(field, lookup),
        )


class CoreAPIURLFilterBackend(URLFilterBackend):
    """
    Same as :py:class:`url_filter.integrations.drf.DjangoFilterBackend` except
    this backend also implements coreapi interface for autogenerated API docs.
    """

    def get_schema_fields(self, view):
        """
        Get coreapi filter definitions

        Returns all filters including their supported lookups.
        """
        filterset = self.get_schema_filterset(view)
        return [] if filterset is None else list(_all_filters(filterset))
